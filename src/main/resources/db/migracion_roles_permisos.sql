-- =====================================================================
--  DBAsset - Roles y permisos configurables desde el superadministrador
--  Idempotente y solo ADITIVA. Se ejecuta al arrancar la aplicación.
--
--  Antes el rol vivía como texto libre en usuario_empresa.rol_en_empresa
--  ('ADMIN' / 'AUDITOR'). Ahora existe un catálogo global de roles y un
--  catálogo de permisos (módulo + acción) que el superadmin puede editar.
--  La columna rol_en_empresa se conserva por compatibilidad y se mantiene
--  sincronizada con el nombre del rol elegido.
-- =====================================================================

-- ---------------------------------------------------------------------
--  Catálogo de roles (global para todas las empresas)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.rol (
    cod_rol      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(50)  NOT NULL UNIQUE,
    descripcion  VARCHAR(255),
    es_sistema   BOOLEAN      NOT NULL DEFAULT FALSE,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
--  Catálogo de permisos: cada permiso es un módulo + una acción.
--  Ej.: activos.ver, activos.crear, reportes.ver.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.permiso (
    cod_permiso  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(100) NOT NULL UNIQUE,
    modulo       VARCHAR(50)  NOT NULL,
    accion       VARCHAR(30)  NOT NULL,
    descripcion  VARCHAR(200),
    orden        INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS dbasset.rol_permiso (
    cod_rol      INTEGER NOT NULL,
    cod_permiso  INTEGER NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (cod_rol, cod_permiso),
    CONSTRAINT fk_rp_rol     FOREIGN KEY (cod_rol)     REFERENCES dbasset.rol (cod_rol)         ON DELETE CASCADE,
    CONSTRAINT fk_rp_permiso FOREIGN KEY (cod_permiso) REFERENCES dbasset.permiso (cod_permiso) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
--  Rol asignado al usuario dentro de cada empresa
-- ---------------------------------------------------------------------
ALTER TABLE dbasset.usuario_empresa
    ADD COLUMN IF NOT EXISTS cod_rol INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_ue_rol'
    ) THEN
        ALTER TABLE dbasset.usuario_empresa
            ADD CONSTRAINT fk_ue_rol FOREIGN KEY (cod_rol) REFERENCES dbasset.rol (cod_rol);
    END IF;
END $$;

