INSERT INTO dbasset.rol (nombre, descripcion, es_sistema, activo) VALUES
    ('ADMIN',   'Administrador: acceso completo a la empresa', TRUE, TRUE),
    ('AUDITOR', 'Auditor: solo consulta, sin modificar información', TRUE, TRUE)
ON CONFLICT (nombre) DO NOTHING;

-- ADMIN recibe todos los permisos (incluidos los nuevos que se agreguen a futuro)
INSERT INTO dbasset.rol_permiso (cod_rol, cod_permiso)
SELECT r.cod_rol, p.cod_permiso
FROM dbasset.rol r CROSS JOIN dbasset.permiso p
WHERE r.nombre = 'ADMIN'
ON CONFLICT DO NOTHING;

-- AUDITOR recibe solo los permisos de consulta (acción "ver")
INSERT INTO dbasset.rol_permiso (cod_rol, cod_permiso)
SELECT r.cod_rol, p.cod_permiso
FROM dbasset.rol r JOIN dbasset.permiso p ON p.accion = 'ver'
WHERE r.nombre = 'AUDITOR'
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------------
--  Migración de los roles existentes (texto -> catálogo)
-- ---------------------------------------------------------------------
UPDATE dbasset.usuario_empresa ue
SET cod_rol = r.cod_rol
FROM dbasset.rol r
WHERE ue.cod_rol IS NULL
  AND UPPER(COALESCE(TRIM(ue.rol_en_empresa), 'ADMIN')) = r.nombre;

-- Asignaciones sin rol reconocible pasan a ADMIN para no perder acceso
UPDATE dbasset.usuario_empresa ue
SET cod_rol = (SELECT cod_rol FROM dbasset.rol WHERE nombre = 'ADMIN')
WHERE ue.cod_rol IS NULL;

CREATE INDEX IF NOT EXISTS idx_usuario_empresa_rol ON dbasset.usuario_empresa (cod_rol);
CREATE INDEX IF NOT EXISTS idx_rol_permiso_rol         ON dbasset.rol_permiso (cod_rol);
