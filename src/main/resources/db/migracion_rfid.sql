-- =====================================================================
--  DBAsset - Migración RFID (Fase 1)
--  Idempotente y solo ADITIVA: no borra ni modifica datos existentes.
--  Se ejecuta sola al arrancar el backend (spring.sql.init.mode=always).
--  También puede correrse a mano:  psql -d dbasset -f migracion_rfid.sql
--
--  IMPORTANTE: Spring separa sentencias por ';'. No usar bloques DO $$.
-- =====================================================================

-- ---------------------------------------------------------------------
--  1. Maestro de activos: EPC, categoría y situación (ACTIVO / INACTIVO)
-- ---------------------------------------------------------------------
ALTER TABLE dbasset.m_activos ADD COLUMN IF NOT EXISTS epc        VARCHAR(128);
ALTER TABLE dbasset.m_activos ADD COLUMN IF NOT EXISTS categoria  VARCHAR(100);
ALTER TABLE dbasset.m_activos ADD COLUMN IF NOT EXISTS situacion  VARCHAR(15) NOT NULL DEFAULT 'ACTIVO';

-- Un EPC no puede repetirse dentro de la misma empresa (sí puede ser NULL).
CREATE UNIQUE INDEX IF NOT EXISTS uq_activo_empresa_epc
    ON dbasset.m_activos (cod_empresa, epc) WHERE epc IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_activos_situacion ON dbasset.m_activos (cod_empresa, situacion);

-- Campos nuevos en el asistente de importación (solo empresas que ya tienen configuración).
INSERT INTO dbasset.configuracion_campo (cod_empresa, nombre_campo_bd, etiqueta_usuario, es_visible, es_obligatorio, orden)
SELECT e.cod_empresa, c.nombre_campo_bd, c.etiqueta_usuario, TRUE, FALSE, c.orden
FROM (VALUES ('epc', 'EPC (tag RFID)', 16), ('categoria', 'Categoría', 17))
     AS c(nombre_campo_bd, etiqueta_usuario, orden)
CROSS JOIN (SELECT DISTINCT cod_empresa FROM dbasset.configuracion_campo) e
WHERE NOT EXISTS (
    SELECT 1 FROM dbasset.configuracion_campo cc
    WHERE cc.cod_empresa = e.cod_empresa AND cc.nombre_campo_bd = c.nombre_campo_bd
);

-- ---------------------------------------------------------------------
--  2. Fotos del activo (evidencia de alta). El archivo vive en disco
--     (dbasset.archivos.dir); aquí solo la ruta relativa.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.activo_foto (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa     INTEGER      NOT NULL,
    id_activo       INTEGER      NOT NULL,
    nombre_original VARCHAR(255),
    ruta            VARCHAR(500) NOT NULL,
    tipo_mime       VARCHAR(100),
    tamano          BIGINT,
    registrado_por  VARCHAR(200),
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_foto_activo FOREIGN KEY (id_activo) REFERENCES dbasset.m_activos (id)
);
CREATE INDEX IF NOT EXISTS idx_foto_activo ON dbasset.activo_foto (id_activo);

-- ---------------------------------------------------------------------
--  3. Inventario RFID: sesión, foto de lo esperado, lecturas y lotes
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.inventario_sesion (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa     INTEGER      NOT NULL,
    descripcion     VARCHAR(255) NOT NULL,
    alcance         VARCHAR(15)  NOT NULL,          -- COMPLETO | LOCAL | AREA | OFICINA
    cod_local       INTEGER,
    cod_area        INTEGER,
    cod_oficina     INTEGER,
    estado          VARCHAR(15)  NOT NULL DEFAULT 'ABIERTA',   -- ABIERTA | CERRADA
    total_esperados INTEGER      NOT NULL DEFAULT 0,
    creado_por      VARCHAR(200),
    fecha_creacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cerrado_por     VARCHAR(200),
    fecha_cierre    TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inv_sesion_empresa ON dbasset.inventario_sesion (cod_empresa, estado);

-- Activos que DEBERÍAN encontrarse (copia tomada al crear la sesión).
CREATE TABLE IF NOT EXISTS dbasset.inventario_esperado (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion       INTEGER      NOT NULL,
    id_activo       INTEGER      NOT NULL,
    cod_activo      VARCHAR(100),
    epc             VARCHAR(128),
    cod_local       INTEGER,
    cod_area        INTEGER,
    cod_oficina     INTEGER,
    cod_responsable INTEGER,
    CONSTRAINT fk_esp_sesion FOREIGN KEY (id_sesion) REFERENCES dbasset.inventario_sesion (id),
    CONSTRAINT uq_esp_sesion_activo UNIQUE (id_sesion, id_activo)
);

-- EPC leídos en la sesión (uno por EPC; se acumula el conteo).
CREATE TABLE IF NOT EXISTS dbasset.inventario_lectura (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion         INTEGER      NOT NULL,
    epc               VARCHAR(128) NOT NULL,
    conteo            INTEGER      NOT NULL DEFAULT 1,
    rssi              INTEGER,
    primera_lectura   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultima_lectura    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cod_area_lectura  INTEGER,                      -- zona donde se leyó (opcional, la manda la app)
    dispositivo       VARCHAR(100),
    cod_inventariador INTEGER,
    origen            VARCHAR(15)  NOT NULL DEFAULT 'APP', -- APP | ARCHIVO | MANUAL
    CONSTRAINT fk_lec_sesion FOREIGN KEY (id_sesion) REFERENCES dbasset.inventario_sesion (id),
    CONSTRAINT uq_lec_sesion_epc UNIQUE (id_sesion, epc)
);

-- Lotes ya procesados: si la app reenvía el mismo lote (sync offline) no se duplica.
CREATE TABLE IF NOT EXISTS dbasset.inventario_lote (
    id_sesion       INTEGER      NOT NULL,
    id_lote         VARCHAR(100) NOT NULL,
    lecturas        INTEGER      NOT NULL DEFAULT 0,
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inventario_lote PRIMARY KEY (id_sesion, id_lote),
    CONSTRAINT fk_lote_sesion FOREIGN KEY (id_sesion) REFERENCES dbasset.inventario_sesion (id)
);

-- ---------------------------------------------------------------------
--  4. Transferencias entre áreas (con confirmación de recepción)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.transferencia (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa           INTEGER      NOT NULL,
    id_activo             INTEGER      NOT NULL,
    cod_activo            VARCHAR(100),
    cod_local_origen      INTEGER,
    cod_area_origen       INTEGER,
    cod_oficina_origen    INTEGER,
    cod_resp_origen       INTEGER,
    cod_local_destino     INTEGER,
    cod_area_destino      INTEGER      NOT NULL,
    cod_oficina_destino   INTEGER,
    cod_resp_destino      INTEGER,                  -- responsable de la recepción
    motivo                VARCHAR(500),
    estado                VARCHAR(15)  NOT NULL DEFAULT 'PENDIENTE', -- PENDIENTE | RECIBIDA | RECHAZADA | ANULADA
    registrado_por        VARCHAR(200),
    origen_registro       VARCHAR(10)  NOT NULL DEFAULT 'WEB',       -- WEB | APP
    fecha_envio           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recibido_por          VARCHAR(200),
    fecha_recepcion       TIMESTAMP,
    observacion_recepcion VARCHAR(500),
    CONSTRAINT fk_transf_activo FOREIGN KEY (id_activo) REFERENCES dbasset.m_activos (id)
);
CREATE INDEX IF NOT EXISTS idx_transf_empresa ON dbasset.transferencia (cod_empresa, estado);
CREATE INDEX IF NOT EXISTS idx_transf_activo  ON dbasset.transferencia (id_activo);

-- ---------------------------------------------------------------------
--  5. Bajas de activos y sus adjuntos de sustento
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dbasset.baja_activo (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa       INTEGER      NOT NULL,
    id_activo         INTEGER      NOT NULL,
    cod_activo        VARCHAR(100),
    motivo            VARCHAR(20)  NOT NULL,        -- OBSOLESCENCIA | PERDIDA | VENTA | DESTRUCCION | OTRO
    detalle           VARCHAR(1000),
    autorizado_por    VARCHAR(200) NOT NULL,
    registrado_por    VARCHAR(200),
    fecha_baja        DATE         NOT NULL,
    fecha_registro    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cod_local         INTEGER,
    cod_area          INTEGER,
    cod_oficina       INTEGER,
    cod_responsable   INTEGER,
    CONSTRAINT fk_baja_activo FOREIGN KEY (id_activo) REFERENCES dbasset.m_activos (id)
);
CREATE INDEX IF NOT EXISTS idx_baja_empresa ON dbasset.baja_activo (cod_empresa, fecha_baja);
CREATE INDEX IF NOT EXISTS idx_baja_activo  ON dbasset.baja_activo (id_activo);

CREATE TABLE IF NOT EXISTS dbasset.baja_adjunto (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_baja         INTEGER      NOT NULL,
    nombre_original VARCHAR(255),
    ruta            VARCHAR(500) NOT NULL,
    tipo_mime       VARCHAR(100),
    tamano          BIGINT,
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_adjunto_baja FOREIGN KEY (id_baja) REFERENCES dbasset.baja_activo (id)
);
CREATE INDEX IF NOT EXISTS idx_adjunto_baja ON dbasset.baja_adjunto (id_baja);
