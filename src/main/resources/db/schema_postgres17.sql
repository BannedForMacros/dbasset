-- =====================================================================
--  DBAsset - Esquema de base de datos para PostgreSQL 17
--  Base de datos sugerida: dbasset   (créala ANTES de correr este script)
--      CREATE DATABASE dbasset;
--      \c dbasset
--      \i schema_postgres17.sql
--  Schema (dentro de la base): dbasset
--  Generado a partir de las entidades JPA del backend (Spring Boot 4 / Java 21)
--
--  NOTA IMPORTANTE sobre el maestro de activos:
--  El UNIQUE de cod_activo es POR EMPRESA (cod_empresa, cod_activo),
--  no global. Esto permite que el MISMO activo se inventaríe en varias
--  cargas distintas (cada carga genera filas en detalle_carga, que NO
--  tiene restriccion de unicidad sobre cod_activo).
-- =====================================================================

-- DROP SCHEMA IF EXISTS dbasset CASCADE;   -- (descomenta para reinstalar desde cero)
CREATE SCHEMA IF NOT EXISTS dbasset;
SET search_path TO dbasset;

-- =====================================================================
--  TABLAS BASE (sin dependencias)
-- =====================================================================

-- Empresas (multi-tenant). cod_empresa es el valor que viaja en X-Tenant-ID.
-- No es una entidad JPA: el backend la consulta por SQL nativo en el login.
CREATE TABLE IF NOT EXISTS dbasset.empresa (
    cod_empresa   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc           VARCHAR(20) UNIQUE,
    razon_social  VARCHAR(255),
    activo        BOOLEAN DEFAULT TRUE,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Usuarios administrativos (login web). Contraseña en TEXTO PLANO (NoOpPasswordEncoder).
CREATE TABLE IF NOT EXISTS dbasset.usuario (
    cod_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario   VARCHAR(100) UNIQUE,
    clave            VARCHAR(255),
    nombre_completo  VARCHAR(200),
    descripcion      VARCHAR(255),
    tipo_usu         INTEGER
);

-- Relación usuario <-> empresa (un usuario puede operar varias empresas).
-- El login usa: WHERE ue.activo = true AND e.activo = true
CREATE TABLE IF NOT EXISTS dbasset.usuario_empresa (
    cod_usuario      INTEGER NOT NULL,
    cod_empresa      INTEGER NOT NULL,
    rol_en_empresa   VARCHAR(50),
    activo           BOOLEAN DEFAULT TRUE,
    CONSTRAINT pk_usuario_empresa PRIMARY KEY (cod_usuario, cod_empresa),
    CONSTRAINT fk_ue_usuario FOREIGN KEY (cod_usuario) REFERENCES dbasset.usuario (cod_usuario),
    CONSTRAINT fk_ue_empresa FOREIGN KEY (cod_empresa) REFERENCES dbasset.empresa (cod_empresa)
);

-- Catalogo de estados de un activo (Bueno, Regular, Malo, etc.)
CREATE TABLE IF NOT EXISTS dbasset.estado (
    cod_estado  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado      VARCHAR(100)
);

-- Catalogo de colores
CREATE TABLE IF NOT EXISTS dbasset.color (
    cod_color     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_color  VARCHAR(100) NOT NULL UNIQUE
);

-- Catalogo de marcas
CREATE TABLE IF NOT EXISTS dbasset.marca (
    cod_marca     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_marca  VARCHAR(100) NOT NULL UNIQUE
);

-- Inventariadores (usuarios moviles de campo)
CREATE TABLE IF NOT EXISTS dbasset.inventariador (
    cod_inventariador     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_inventariador  VARCHAR(200) NOT NULL,
    dni                   VARCHAR(20),
    telefono              VARCHAR(30),
    email                 VARCHAR(150),
    cod_interno           VARCHAR(50),
    usuario               VARCHAR(100) UNIQUE,
    clave                 VARCHAR(255),
    cod_empresa           INTEGER NOT NULL,
    activo                BOOLEAN DEFAULT TRUE,
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Responsables / custodios de activos
CREATE TABLE IF NOT EXISTS dbasset.responsable (
    cod_responsable  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    responsable      VARCHAR(200),
    cargo            VARCHAR(150),
    cod_interno      VARCHAR(50),
    cod_empresa      INTEGER,
    activo           BOOLEAN DEFAULT TRUE,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================================
--  JERARQUIA DE UBICACIONES: Local -> Area -> Oficina
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.local (
    cod_local    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa  INTEGER NOT NULL,
    local        VARCHAR(200),
    direccion    VARCHAR(255),
    cod_interno  VARCHAR(50),
    activo       BOOLEAN DEFAULT TRUE,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dbasset.area (
    cod_area     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa  INTEGER NOT NULL,
    area         VARCHAR(200),
    observacion  VARCHAR(255),
    cod_interno  VARCHAR(50),
    cod_local    INTEGER NOT NULL,
    activo       BOOLEAN DEFAULT TRUE,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_area_local FOREIGN KEY (cod_local) REFERENCES dbasset.local (cod_local)
);

CREATE TABLE IF NOT EXISTS dbasset.oficina (
    cod_oficina  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa  INTEGER NOT NULL,
    oficina      VARCHAR(200),
    observacion  VARCHAR(255),
    cod_interno  VARCHAR(50),
    cod_local    INTEGER,
    cod_area     INTEGER NOT NULL,
    activo       BOOLEAN DEFAULT TRUE,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_oficina_area  FOREIGN KEY (cod_area)  REFERENCES dbasset.area  (cod_area),
    CONSTRAINT fk_oficina_local FOREIGN KEY (cod_local) REFERENCES dbasset.local (cod_local)
);

-- Relacion muchos-a-muchos: un responsable puede estar en varias oficinas
CREATE TABLE IF NOT EXISTS dbasset.responsable_oficina (
    cod_responsable  INTEGER NOT NULL,
    cod_oficina      INTEGER NOT NULL,
    CONSTRAINT pk_responsable_oficina PRIMARY KEY (cod_responsable, cod_oficina),
    CONSTRAINT fk_ro_responsable FOREIGN KEY (cod_responsable) REFERENCES dbasset.responsable (cod_responsable),
    CONSTRAINT fk_ro_oficina     FOREIGN KEY (cod_oficina)     REFERENCES dbasset.oficina     (cod_oficina)
);

-- =====================================================================
--  MAESTRO DE ACTIVOS
--  UNIQUE por (cod_empresa, cod_activo)  <-- clave para tu caso
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.m_activos (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa        INTEGER NOT NULL,
    cod_activo         VARCHAR(100) NOT NULL,
    cod_interno        VARCHAR(50),
    descripcion        VARCHAR(255),
    marca              VARCHAR(100),
    modelo             VARCHAR(100),
    tipo               VARCHAR(100),
    color              VARCHAR(100),
    cod_color          VARCHAR(50),
    dimensiones        VARCHAR(100),
    serie              VARCHAR(100),
    n_motor            VARCHAR(100),
    n_chasis           VARCHAR(100),
    placa              VARCHAR(50),
    anio               VARCHAR(10),
    fecha_compra       VARCHAR(30),
    obs                VARCHAR(255),
    cod_local          INTEGER,
    cod_area           INTEGER,
    cod_oficina        INTEGER,
    cod_responsable    INTEGER,
    cod_inventariador  INTEGER,
    cod_estado         INTEGER,
    activo             BOOLEAN DEFAULT TRUE,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_activo_empresa_codigo UNIQUE (cod_empresa, cod_activo),
    CONSTRAINT fk_activo_local         FOREIGN KEY (cod_local)         REFERENCES dbasset.local         (cod_local),
    CONSTRAINT fk_activo_area          FOREIGN KEY (cod_area)          REFERENCES dbasset.area          (cod_area),
    CONSTRAINT fk_activo_oficina       FOREIGN KEY (cod_oficina)       REFERENCES dbasset.oficina       (cod_oficina),
    CONSTRAINT fk_activo_responsable   FOREIGN KEY (cod_responsable)   REFERENCES dbasset.responsable   (cod_responsable),
    CONSTRAINT fk_activo_inventariador FOREIGN KEY (cod_inventariador) REFERENCES dbasset.inventariador (cod_inventariador),
    CONSTRAINT fk_activo_estado        FOREIGN KEY (cod_estado)        REFERENCES dbasset.estado        (cod_estado)
);

-- =====================================================================
--  CARGAS (campañas de inventariado) y su detalle
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.cargas (
    cod_carga    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa  INTEGER NOT NULL,
    descripcion  VARCHAR(255),
    estado       VARCHAR(2),                 -- 'C' Creada, 'A' Asignada, 'T' Terminada
    fecha        VARCHAR(20),                -- formato dd/MM/yyyy (como lo guarda el backend)
    activo       BOOLEAN DEFAULT TRUE,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Detalle de carga: UNA fila por activo POR carga.
-- Sin UNIQUE sobre cod_activo -> el mismo activo puede repetirse en cargas distintas.
CREATE TABLE IF NOT EXISTS dbasset.detalle_carga (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_carga            INTEGER,
    cod_activo           VARCHAR(100),
    inventariado         VARCHAR(2),
    cod_estado           INTEGER,
    cod_usuario          INTEGER,
    fechainventario      VARCHAR(30),
    obs                  VARCHAR(200),
    nuevo                INTEGER,
    impreso              INTEGER,
    modificado           INTEGER,
    cod_responsable      INTEGER,
    cod_inventariador    INTEGER,
    cod_local_reubica    INTEGER,
    cod_area_reubica     INTEGER,
    cod_oficina_reubica  INTEGER,
    cod_resp_reubica     INTEGER,
    CONSTRAINT fk_detalle_carga         FOREIGN KEY (cod_carga)         REFERENCES dbasset.cargas        (cod_carga),
    CONSTRAINT fk_detalle_usuario       FOREIGN KEY (cod_usuario)       REFERENCES dbasset.usuario       (cod_usuario),
    CONSTRAINT fk_detalle_responsable   FOREIGN KEY (cod_responsable)   REFERENCES dbasset.responsable   (cod_responsable),
    CONSTRAINT fk_detalle_inventariador FOREIGN KEY (cod_inventariador) REFERENCES dbasset.inventariador (cod_inventariador)
    -- OPCIONAL: si quieres impedir el mismo activo DOS veces en la MISMA carga
    -- (pero permitirlo entre cargas distintas), descomenta:
    -- , CONSTRAINT uq_detalle_carga_activo UNIQUE (cod_carga, cod_activo)
);

-- =====================================================================
--  FIRMAS DE CONFORMIDAD POR CARGA
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.carga_firmas (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_carga       INTEGER NOT NULL,
    cod_local       VARCHAR(50),
    cod_area        VARCHAR(50),
    cod_oficina     VARCHAR(50),
    cod_responsable INTEGER NOT NULL,
    firma           TEXT NOT NULL,           -- imagen de firma en Base64
    fecha_registro  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_firma_carga FOREIGN KEY (cod_carga) REFERENCES dbasset.cargas (cod_carga)
);

-- =====================================================================
--  HISTORIAL DE REUBICACIONES
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.reubicacion (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_carga             INTEGER,
    cod_activo            VARCHAR(100),
    cod_inventariador     INTEGER,
    cod_local_anterior    INTEGER,
    cod_area_anterior     INTEGER,
    cod_oficina_anterior  INTEGER,
    cod_resp_anterior     INTEGER,
    cod_local_nuevo       INTEGER,
    cod_area_nuevo        INTEGER,
    cod_oficina_nuevo     INTEGER,
    cod_resp_nuevo        INTEGER,
    estado                VARCHAR(50),
    observacion           VARCHAR(255),
    fecha_reubicacion     VARCHAR(30),
    fecha_registro        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================================
--  CONFIGURACION DINAMICA DE CAMPOS (por empresa)
-- =====================================================================

CREATE TABLE IF NOT EXISTS dbasset.configuracion_campo (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa      INTEGER,
    nombre_campo_bd  VARCHAR(100),
    etiqueta_usuario VARCHAR(150),
    es_visible       BOOLEAN,
    es_obligatorio   BOOLEAN,
    orden            INTEGER
);

-- =====================================================================
--  INDICES recomendados (consultas multi-tenant y por carga)
-- =====================================================================

CREATE INDEX IF NOT EXISTS idx_activos_empresa        ON dbasset.m_activos     (cod_empresa);
CREATE INDEX IF NOT EXISTS idx_activos_codigo         ON dbasset.m_activos     (cod_activo);
CREATE INDEX IF NOT EXISTS idx_cargas_empresa         ON dbasset.cargas        (cod_empresa);
CREATE INDEX IF NOT EXISTS idx_detalle_carga          ON dbasset.detalle_carga (cod_carga);
CREATE INDEX IF NOT EXISTS idx_detalle_activo         ON dbasset.detalle_carga (cod_activo);
CREATE INDEX IF NOT EXISTS idx_local_empresa          ON dbasset.local         (cod_empresa);
CREATE INDEX IF NOT EXISTS idx_area_local             ON dbasset.area          (cod_local);
CREATE INDEX IF NOT EXISTS idx_oficina_area           ON dbasset.oficina       (cod_area);
CREATE INDEX IF NOT EXISTS idx_inventariador_empresa  ON dbasset.inventariador (cod_empresa);
CREATE INDEX IF NOT EXISTS idx_reubicacion_carga      ON dbasset.reubicacion   (cod_carga);
CREATE INDEX IF NOT EXISTS idx_usuario_empresa_user   ON dbasset.usuario_empresa (cod_usuario);
CREATE INDEX IF NOT EXISTS idx_usuario_empresa_emp    ON dbasset.usuario_empresa (cod_empresa);

-- =====================================================================
--  SEED MINIMO (el backend usa cod_estado = 1 por defecto al importar)
-- =====================================================================

INSERT INTO dbasset.estado (cod_estado, estado) VALUES
    (1, 'BUENO'),
    (2, 'REGULAR'),
    (3, 'MALO')
ON CONFLICT (cod_estado) DO NOTHING;

-- Reajustar la secuencia de identidad de estado tras el seed con IDs explicitos
SELECT setval(pg_get_serial_sequence('dbasset.estado', 'cod_estado'),
              (SELECT COALESCE(MAX(cod_estado), 1) FROM dbasset.estado));
